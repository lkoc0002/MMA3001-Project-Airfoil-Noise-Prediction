"""Functions for evaluating regression model performance."""

import time

import numpy as np
from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score,
)


def evaluate_regression(y_true, y_pred):
    """
    Calculate performance metrics for a regression model.

    Parameters
    ----------
    y_true : array-like
        Measured output values.
    y_pred : array-like
        Predicted output values generated by the regression model.

    Returns
    -------
    metrics : dict
        Dictionary containing MAE, RMSE and R-squared performance metrics.
    """
    # Calculate complementary metrics to assess prediction error and model fit
    mae = mean_absolute_error(y_true, y_pred)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))
    r2 = r2_score(y_true, y_pred)

    metrics = {
        "MAE": mae,
        "RMSE": rmse,
        "R2": r2,
    }

    return metrics


def average_prediction_time(model, X_data, repetitions=100):
    """
    Calculate the average prediction time of a regression model.

    Parameters
    ----------
    model : regression model
        The fitted regression model used to generate predictions.
    X_data : pandas.DataFrame or numpy.ndarray
        Input data used for prediction.
    repetitions : int, optional
        Number of repeated predictions used to calculate the average runtime.
        The default is 100.

    Returns
    -------
    average_time : float
        Average prediction time in milliseconds.
    """
    start = time.perf_counter()

    # Repeat predictions to reduce the influence of small timing fluctuations
    for _ in range(repetitions):
        model.predict(X_data)

    total_time = time.perf_counter() - start

    # Convert average prediction time from seconds to milliseconds
    average_time = (total_time / repetitions) * 1000

    return average_time
